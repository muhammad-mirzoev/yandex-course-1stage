from datetime import datetime, timedelta


def observation_day(*dates):
    # Преобразуем все даты в список объектов datetime
    dates = [datetime.strptime(date, "%Y-%m-%d") for date in dates]

    # Сортируем даты по возрастанию
    dates.sort()

    # Для каждой даты проверяем, подходит ли она для наблюдения
    for date in dates:
        # Проверка, чтобы день месяца не был кратен 3
        if date.day % 3 != 0:
            # Находим разницу в днях от текущей даты (предположим, что сейчас 2025-04-13)
            today = datetime(2025, 4, 13)
            delta = (date - today).days

            # Вычисляем день недели: 1 - Понедельник, 2 - Вторник и т.д.
            weekday = date.weekday() + 1  # weekday() возвращает от 0 (Пон) до 6 (Воскр), нам нужно с 1 по 7

            return delta, weekday


# Пример использования
print(observation_day("2020-01-31", "2020-01-18", "2020-02-29"))  # Вывод: (30, 5)
print(observation_day("2020-12-30", "2020-05-01", "2019-12-31"))  # Вывод: (121, 5)

