def choose_coffee(*preferences):
    # Определяем рецепты напитков в виде словаря
    recipes = {
        "Эспрессо": [(1, 0, 0)],  # 1 кофейное зерно
        "Капучино": [(1, 3, 0)],  # 1 кофейное зерно, 3 молока
        "Маккиато": [(2, 1, 0)],  # 2 кофейных зерна, 1 молоко
        "Кофе по-венски": [(1, 0, 2)],  # 1 кофейное зерно, 2 сливки
        "Латте Маккиато": [(1, 2, 1)],  # 1 кофейное зерно, 2 молока, 1 сливка
        "Кон Панна": [(1, 0, 1)]  # 1 кофейное зерно, 1 сливка
    }

    # Преобразуем список ингредиентов
    ingredients = [1, 2, 3]  # Пример доступных ингредиентов (кофейные зерна, молоко, сливки)

    # Перебираем предпочтения
    for drink in preferences:
        # Получаем рецепт напитка
        recipe = recipes.get(drink)

        # Если рецепт существует, проверим, можем ли мы приготовить напиток
        if recipe:
            # Проверяем все ингредиенты для рецепта
            if all(ingredients[i] >= recipe[0][i] for i in range(3)):
                # Если все ингредиенты в достаточном количестве, уменьшаем их
                for i in range(3):
                    ingredients[i] -= recipe[0][i]
                return drink

    # Если не нашли напитка, который можно приготовить
    return "К сожалению, не можем предложить Вам напиток"


